// Bundles the root planner modules for the Android app: android/js/planners.js and everything it imports become one
// classic script in the app's assets, which QuickJS evaluates once (see android/ARCHITECTURE.md, "JS planner bridge").
// Run with `npm run bundle:android`; `--check` exits 1 if the committed bundle is out of date (CI and the tests use it).
import {build} from 'esbuild';
import {readFile, writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
export const OUT = `${root}android/app/src/main/assets/planners.js`;

export async function bundle() {
  const result = await build({
    entryPoints:[`${root}android/js/planners.js`], bundle:true, write:false, format:'iife', target:'es2020', platform:'neutral',
    // Readable on purpose: a stack trace from the phone points at real names and lines, and the size is small anyway.
    minify:false, legalComments:'none', charset:'utf8', logLevel:'silent',
    banner:{js:'// Generated by scripts/bundle-android.mjs from the root planner modules. Do not edit; run npm run bundle:android.'},
  });
  // esbuild writes absolute paths into its comments; keep them relative so the bundle is the same on every machine.
  return result.outputFiles[0].text.replaceAll(root, '');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = await bundle();
  if (process.argv.includes('--check')) {
    const current = await readFile(OUT, 'utf8').catch(() => '');
    if (current !== text) { console.error(`${OUT} is out of date: run npm run bundle:android`); process.exit(1); }
    console.log('Android planner bundle is current.');
  } else {
    await writeFile(OUT, text);
    console.log(`Wrote ${OUT} (${(text.length / 1024).toFixed(0)} kB)`);
  }
}
